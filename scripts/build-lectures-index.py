#!/usr/bin/env python3
"""
lectures/index.html 자동 생성기.

각 lectures/*.html (slides/*.md를 Marp로 export한 정적 덱) 상단 주석
frontmatter(title/date/status/audience/duration/agenda)를 단일 진실원천으로
삼아 카탈로그 페이지를 생성한다. interactives/index.html과 같은 패턴이지만
별도 폴더 — 슬라이드 덱은 계산기/결정트리와 성격이 달라 분리.

실행: python3 scripts/build-lectures-index.py   (repo 루트 기준)
출력: lectures/index.html  (덮어쓰기)
신규 덱 추가: bash scripts/export-slides.sh 로 slides/*.md를 재수출한 뒤 이 스크립트 실행.
"""

import re
import html
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LECTURES = ROOT / "lectures"
OUT = LECTURES / "index.html"

KNOWN_STATUS = {"done", "review", "in-progress", "draft"}
FALLBACK_AUDIENCE = "기타"


def parse_frontmatter(text: str) -> dict:
    m = re.search(r"<!--\s*\n---\s*\n(.*?)\n---\s*\n-->", text, flags=re.S)
    block = m.group(1) if m else text[:800]
    fm = {}
    for line in block.split("\n"):
        km = re.match(r"^([a-zA-Z_]+):\s*(.*)$", line)
        if km:
            key, val = km.group(1), km.group(2).strip()
            val = val.strip('"').strip("'")
            if key not in fm:
                fm[key] = val
    return fm


def collect():
    """덱 목록을 만든다. *-quiz.html은 독립 항목이 아니라 매칭되는 덱의 동반 퀴즈로만
    붙는다 — interactives/index.html과 달리 퀴즈가 자체 카드 섹션을 갖지 않는다."""
    decks = []
    for p in sorted(LECTURES.glob("*.html")):
        if p.name == "index.html" or p.stem.endswith("-quiz"):
            continue
        fm = parse_frontmatter(p.read_text(encoding="utf-8"))
        status = fm.get("status", "draft").strip()
        if status not in KNOWN_STATUS:
            status = "draft"

        quiz_path = LECTURES / f"{p.stem}-quiz.html"
        quiz = None
        if quiz_path.exists():
            qfm = parse_frontmatter(quiz_path.read_text(encoding="utf-8"))
            quiz = {"file": quiz_path.name, "title": qfm.get("title", "자가테스트")}

        decks.append({
            "file": p.name,
            "title": fm.get("title", p.stem),
            "date": fm.get("date", ""),
            "status": status,
            "audience": fm.get("audience", "").strip() or FALLBACK_AUDIENCE,
            "duration": fm.get("duration", "").strip(),
            "quiz": quiz,
        })
    return decks


def render_card(d: dict) -> str:
    title = html.escape(d["title"])
    dur = f'<span class="dur">{html.escape(d["duration"])}</span>' if d["duration"] else ""
    deck_card = (
        f'      <a class="card" href="{d["file"]}">\n'
        f'        <p class="t">{title}</p>\n'
        f'        <div class="meta"><span class="date">{d["date"]}</span>'
        f'<span class="badge {d["status"]}">{d["status"]}</span>{dur}</div>\n'
        f'      </a>'
    )
    if not d["quiz"]:
        return f'    <div class="pair">\n{deck_card}\n    </div>'
    quiz_title = html.escape(d["quiz"]["title"])
    quiz_card = (
        f'      <a class="card quiz" href="{d["quiz"]["file"]}">\n'
        f'        <p class="t">📝 {quiz_title}</p>\n'
        f'        <div class="meta"><span class="badge quiz-badge">자가테스트</span></div>\n'
        f'      </a>'
    )
    return f'    <div class="pair">\n{deck_card}\n{quiz_card}\n    </div>'


def render_section(label: str, items: list) -> str:
    cards = "\n".join(render_card(d) for d in items)
    return (
        f'  <section>\n'
        f'    <h2>{html.escape(label)}</h2>\n'
        f'    <div class="grid">\n{cards}\n    </div>\n'
        f'  </section>'
    )


