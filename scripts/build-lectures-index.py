def main():
    decks = collect()
    total = len(decks)

    by_aud = {}
    for d in decks:
        by_aud.setdefault(d["audience"], []).append(d)
    for items in by_aud.values():
        items.sort(key=lambda x: (x["date"], x["file"]), reverse=True)

    # 오디언스 라벨은 고정 카테고리가 아니라 frontmatter 자유 텍스트라
    # 최신 덱 날짜 기준으로 섹션 순서를 정한다 (기타는 항상 마지막).
    order = sorted(
        (k for k in by_aud if k != FALLBACK_AUDIENCE),
        key=lambda k: max(d["date"] for d in by_aud[k]),
        reverse=True,
    )
    if FALLBACK_AUDIENCE in by_aud:
        order.append(FALLBACK_AUDIENCE)

    sections = [render_section(k, by_aud[k]) for k in order]

    header = (
        f'  <header>\n'
        f'    <h1>강의·교육 슬라이드<span class="count">{total}</span></h1>\n'
        f'    <p class="sub">위키 근거를 기반으로 만든 세미나·직원 교육용 Marp 덱. '
        f'<code>slides/*.md</code>가 소스, 여기 있는 것은 export된 정적 발표 화면입니다.</p>\n'
        f'  </header>\n'
    )

    out = HEAD + header + "\n".join(sections) + FOOTER
    OUT.write_text(out, encoding="utf-8")
    print(f"[build-lectures-index] {total} decks → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
